<?php

    // CONHECENDO ARRAYS EM PHP

    # Criando um array com o mesmo tipo de dado
    $num = [1, 2, 3, 4, 5];

    // Imprimindo o array completo
    print_r($num);
    echo '<br>';

    // Imprimindo um valor específico do array
    echo $num[0]; 
    echo '<br>';

    # Criando um array com tipos de dados diferentes
    $dados = ['Giselle', 21, 1.67, true];

    // Imprimindo o array completo
    print_r($dados);
    echo '<br>';
    echo $dados[0]; 
?>
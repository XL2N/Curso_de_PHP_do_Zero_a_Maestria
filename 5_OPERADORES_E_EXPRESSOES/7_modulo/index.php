<?php

    // CONHECENDO OPERADOR DE MÓDULO (%)
    // resultado do resto da divisão entre dois números

    # Comparação de divisão e Módulo

    // Operador de divisão (/)
    echo 12 / 2;
    echo " DIVISÃO <br>";

    // Operador de módulo (%)
    echo 12 % 2;
    echo " MÓDULO <br>";

    # Exemplos com restos > 0

    echo 13 % 2; // Resto 1
    echo " <br>";
    echo 13 % 5; // Resto 3
    echo " <br>";

    // Com variáveis
    $a = 20;
    $b = 4;
    $c = 12;

    echo $a % $b; // Resto 0
    echo " <br>";
    echo $a % $c; // Resto 8
    echo " <br>";

?>
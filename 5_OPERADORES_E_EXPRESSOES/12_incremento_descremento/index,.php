<?php

    // CONHECENDO OPERADORES DE INCREMENTO E DECREMENTO

    # Variáveis
    $a = 0;
    $b = 0;
    $x = 10;
    $y = 10;

    # Formas de incrementar
    $a++; // com operador
    $b = $b + 1; // com atribuição em operação

    // Exibindo resultados
    echo "A: " . $a . "<br>";
    echo "B: " . $b . "<br>";
    
    # Formas de decrementar
    $x--; // com operador
    $y = $y - 1; // com atribuição em operação

    // Exibindo resultados
    echo "X: " . $x . "<br>";
    echo "Y: " . $y . "<br>";
    
?>
